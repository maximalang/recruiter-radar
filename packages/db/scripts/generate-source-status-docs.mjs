import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), '../../..');
const outputPath = resolve(repoRoot, 'docs/source-status.generated.md');

export function renderSourceStatusDocs({ readiness, policy, credentials }) {
  const sets = [Object.keys(readiness.sources ?? {}), Object.keys(policy ?? {}), Object.keys(credentials.sources ?? {})]
    .map((items) => items.sort());
  if (sets.some((items) => JSON.stringify(items) !== JSON.stringify(sets[0]))) {
    throw new Error('Canonical policy, readiness and credential source sets differ.');
  }

  const sourceIds = [...sets[0]].sort((left, right) => {
    const priority = String(policy[left]?.priority).localeCompare(String(policy[right]?.priority));
    return priority || left.localeCompare(right);
  });
  const liveVerified = sourceIds.filter((id) => readiness.sources[id].live?.state === 'verified').length;
  const configured = sourceIds.filter((id) => ['configured', 'not-required'].includes(credentials.sources[id].runtimeAvailability?.state)).length;
  const classCounts = Object.fromEntries(Object.keys(credentials.classes ?? {}).map((key) => [key, sourceIds.filter((id) => credentials.sources[id].accessClass === key).length]));

  const lines = [
    '# Source status and credential/action matrix',
    '',
    '> Generated by `npm run docs:generate:source-status` from `packages/db/source-policy.json`, `packages/db/source-readiness.json`, and `packages/db/source-credentials.json`. Do not edit this file manually.',
    '',
    `Canonical sources: ${sourceIds.length}. Live-verified: ${liveVerified}. Runtime configured or credential-free: ${configured}. Access classes: ${Object.entries(classCounts).map(([key, value]) => `${key}=${value}`).join(', ')}.`,
    '',
    '## Operational readiness',
    '',
    '| Source | Priority | Lead eligibility | Promotion | Implementation | Configuration | Live proof | Blockers |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...sourceIds.map((id) => {
      const ready = readiness.sources[id];
      const sourcePolicy = policy[id];
      return row([
        id,
        sourcePolicy.priority,
        sourcePolicy.leadEligibility,
        sourcePolicy.promotionStatus,
        ready.implementation,
        ready.configuration?.mode ?? 'unspecified',
        ready.live?.state ?? 'unspecified',
        ready.blockers?.length ? ready.blockers.join('; ') : 'none',
      ]);
    }),
    '',
    '## Credential and user-action matrix',
    '',
    'Environment variable names are listed for configuration; values are never read into this document.',
    '',
    '| Source | Access | Registration | Credentials | Runtime configured | Live verified | User action | Verifier |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...sourceIds.map((id) => {
      const credential = credentials.sources[id];
      const names = (credential.credentialSets ?? []).flatMap((set) => set.names ?? []);
      return row([
        id,
        `${credential.accessClass} (${credentials.classes[credential.accessClass]})`,
        credential.registration,
        names.length ? [...new Set(names)].join(', ') : 'none',
        ['configured', 'not-required'].includes(credential.runtimeAvailability?.state) ? 'yes' : 'no',
        readiness.sources[id].live?.state === 'verified' ? 'yes' : 'no',
        userAction(id, credential),
        credential.verifier ?? 'none',
      ]);
    }),
    '',
    '## Interpretation boundaries',
    '',
    '- `live-verified` is evidence recorded in the readiness manifest; it is separate from reachability, configuration, deployment, and current production scheduling.',
    '- Class A is credential-free public access. Class B needs free registration. Class C needs explicit permission, an official subscription, or a compliant provider. Class D is not an implementation target.',
    '- Context-only and never-lead-originating sources cannot independently create a delivered lead.',
    '- A missing optional context-source credential is not a launch blocker unless product scope explicitly promotes that source.',
    '',
  ];
  return lines.join('\n');
}

function userAction(id, credential) {
  if (id === 'hh') return 'Wait for the current HH application review; do not submit another registration. After approval, configure HH_CLIENT_ID and HH_CLIENT_SECRET and run the verifier.';
  if (id === 'superjob') return 'SuperJob is already registered and configured; no user action. Re-run the verifier only after runtime changes.';
  if (id === 'youtube-company-channels') return 'Optional: create a free Google Cloud project, enable YouTube Data API v3, and configure YOUTUBE_API_KEY.';
  if (id === 'telegram-company-channels') return 'Optional: register one Telegram application and authorize the least-privilege MTProto session used by the runtime.';
  if (credential.accessClass === 'C') return 'Optional/provider-dependent: approve the lawful provider or official subscription before configuring this source.';
  if (credential.runtimeAvailability?.state === 'missing') return 'Complete the stated free registration and configure only the listed credential names.';
  return 'None.';
}

function row(values) {
  return `| ${values.map(cell).join(' | ')} |`;
}

function cell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function loadJson(relativePath) {
  return JSON.parse(readFileSync(resolve(repoRoot, relativePath), 'utf8'));
}

export function generateSourceStatusDocs({ check = false } = {}) {
  const content = renderSourceStatusDocs({
    readiness: loadJson('packages/db/source-readiness.json'),
    policy: loadJson('packages/db/source-policy.json'),
    credentials: loadJson('packages/db/source-credentials.json'),
  });
  if (check) {
    if (readFileSync(outputPath, 'utf8') !== content) throw new Error('docs/source-status.generated.md is stale. Run npm run docs:generate:source-status.');
  } else {
    writeFileSync(outputPath, content, 'utf8');
  }
  return content;
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  generateSourceStatusDocs({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Source status docs are current.' : 'Generated docs/source-status.generated.md.');
}
